/**
 * Convenient high-level ShadcnSelect component wrapper around Radix Select
 */
export interface SimpleSelectOption {
  value: string;
  label: React.ReactNode;
  disabled?: boolean;
}

export interface ShadcnSelectProps {
  value?: string;
  defaultValue?: string;
  onValueChange: (val: string) => void;
  options: (SimpleSelectOption | string)[];
  placeholder?: string;
  className?: string;
  triggerClassName?: string;
  contentClassName?: string;
  disabled?: boolean;
  id?: string;
}

export const ShadcnSelect: React.FC<ShadcnSelectProps> = ({
  value,
  defaultValue,
  onValueChange,
  options,
  placeholder = "请选择...",
  className,
  triggerClassName,
  contentClassName,
  disabled,
  id,
}) => {
  const normalizedOptions: SimpleSelectOption[] = options.map((opt) =>
    typeof opt === "string" ? { value: opt, label: opt } : opt
  );

  return (
    <div className={cn("relative inline-block w-full", className)}>
      <Select
        value={value}
        defaultValue={defaultValue}
        onValueChange={onValueChange}
        disabled={disabled}
      >
        <SelectTrigger id={id} className={triggerClassName}>
          <SelectValue placeholder={placeholder} />
        </SelectTrigger>
        <SelectContent className={contentClassName}>
          {normalizedOptions.map((opt) => (
            <SelectItem
              key={opt.value}
              value={opt.value}
              disabled={opt.disabled}
            >
              {opt.label}
            </SelectItem>
          ))}
        </SelectContent>
      </Select>
    </div>
  );
};

export {
  Select,
  SelectGroup,
  SelectValue,
  SelectTrigger,
  SelectContent,
  SelectLabel,
  SelectItem,
  SelectSeparator,
  SelectScrollUpButton,
  SelectScrollDownButton,
};
